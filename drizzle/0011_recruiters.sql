CREATE TABLE `gm_recruiter_accounts` (
  `id` int NOT NULL AUTO_INCREMENT,
  `email` varchar(320) NOT NULL,
  `password_hash` varchar(128) NOT NULL,
  `password_salt` varchar(64) NOT NULL,
  `contact_name` varchar(150) NOT NULL,
  `phone` varchar(40) NOT NULL,
  `company_name` varchar(240) NOT NULL,
  `location` varchar(240) NOT NULL,
  `business_details` text NOT NULL,
  `member_count` int NOT NULL,
  `tier` enum('small','medium','large') NOT NULL,
  `price_tsh` int NOT NULL,
  `application_status` enum('pending','approved','rejected') NOT NULL DEFAULT 'pending',
  `payment_status` enum('unsubmitted','submitted','verified','rejected') NOT NULL DEFAULT 'unsubmitted',
  `payment_verified` boolean NOT NULL DEFAULT false,
  `approved` boolean NOT NULL DEFAULT false,
  `access_status` enum('pending','approved','rejected') NOT NULL DEFAULT 'pending',
  `payer_phone` varchar(40),
  `payment_reference` varchar(160),
  `is_active` boolean NOT NULL DEFAULT true,
  `created_at` timestamp NOT NULL DEFAULT (now()),
  `updated_at` timestamp NOT NULL DEFAULT (now()) ON UPDATE CURRENT_TIMESTAMP,
  CONSTRAINT `gm_recruiter_accounts_id` PRIMARY KEY (`id`),
  CONSTRAINT `gm_recruiter_accounts_email_unique` UNIQUE (`email`)
);
